def test_dashboard_shows_recent_incidents(_client):
    """AC-2: After creating incidents via API, dashboard lists them in recently-updated."""
    svc_r = _client.post("/api/services/", json={"name": "DashSvc", "description": "", "team": "ops"})
    svc_id = svc_r.json()["id"]

    for i in range(6):
        _client.post(
            "/api/incidents/",
            json={"title": f"Dash Incident {i}", "service_id": svc_id, "severity": "SEV2", "description": ""},
        )

    r = _client.get("/dashboard")
    assert r.status_code == 200
    assert "recently" in r.text.lower()
    assert "Dash Incident" in r.text


