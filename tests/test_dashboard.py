def test_svg_builder_produces_svg():
    """AC-4: svg_builder.build_bar_chart() returns valid SVG markup."""
    from datetime import date, timedelta

    from app.svg_builder import build_bar_chart

    today = date.today()
    counts = {today.isoformat(): 3, (today - timedelta(days=1)).isoformat(): 1}
    svg = build_bar_chart(counts, days=14)
    assert "<svg" in svg
    assert "<rect" in svg
    assert "</svg>" in svg


def test_svg_builder_empty_counts():
    """AC-4: svg_builder works with no incidents (all zero counts)."""
    from app.svg_builder import build_bar_chart  # noqa: PLC0415

    svg = build_bar_chart({}, days=14)
    assert "<svg" in svg
    assert "</svg>" in svg


